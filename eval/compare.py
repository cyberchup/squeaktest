"""Compare the shortlisted models on the same clips: the Phase 2 bake-off (decision D17).

    uv run --group eval python -m eval.compare

Reads each model's cached scores (written by eval.score) and writes eval/results/bakeoff.md:
headline numbers per model and condition, then each model's difference from the default model
with paired speaker-bootstrap intervals. Test speakers only.

Paired, because all models score the same clips: each resample draws one set of speakers and
measures every model on it, so the speakers' difficulty cancels out of the difference.
"""

from __future__ import annotations

import argparse
from collections.abc import Callable
from pathlib import Path

import numpy as np

from eval.analyze import (
    RESULTS_DIR,
    Policy,
    Scored,
    _eer,
    _tpr_at,
    load_records,
    score_records,
    split_mask,
)
from eval.datasets import read_dev_speakers
from eval.degrade import CONDITIONS
from squeaktest.config import Settings
from squeaktest.metrics import Interval, paired_bootstrap
from squeaktest.model import DEFAULT_MODEL, MODELS

METRICS: dict[str, Callable[[np.ndarray, np.ndarray], float]] = {
    "EER": _eer,
    "Fakes caught at 1% FPR": _tpr_at(0.01),
}


def load_test(data_dir: Path, model: str, condition: str) -> Scored | None:
    """A model's test-speaker clips under one condition, or None if they weren't scored."""
    scores_dir = Path(data_dir) / "eval" / "scores" / model / "in-the-wild"
    if condition == "clean":
        path = scores_dir / "clean-all.jsonl"
    else:
        path = scores_dir / f"{condition}-test-n3000.jsonl"
    if not path.exists():
        return None
    scored = score_records(load_records(path), Policy())
    return scored.subset(split_mask(scored, read_dev_speakers(), "test"))


def align(a: Scored, b: Scored) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    """Labels, speakers and both models' scores on the clips both of them assessed."""
    _, ia, ib = np.intersect1d(a.ids, b.ids, assume_unique=True, return_indices=True)
    if not np.array_equal(a.labels[ia], b.labels[ib]):
        raise ValueError("the two score files disagree on labels")
    return a.labels[ia], a.speakers[ia], a.scores[ia], b.scores[ib]


def compare(data_dir: Path, models: list[str], baseline: str, n_boot: int) -> dict:
    results: dict = {"baseline": baseline, "models": models, "conditions": {}}
    for condition, spec in CONDITIONS.items():
        scored = {m: load_test(data_dir, m, condition) for m in models}
        if any(s is None for s in scored.values()):
            continue
        entry: dict = {"description": spec.description, "metrics": {}, "vs_baseline": {}}
        for m, s in scored.items():
            entry["metrics"][m] = {name: f(s.labels, s.scores) for name, f in METRICS.items()}
            entry["metrics"][m]["clips"] = int(s.labels.size)
        for m in models:
            if m == baseline:
                continue
            labels, speakers, other, base = align(scored[m], scored[baseline])
            entry["vs_baseline"][m] = {
                name: paired_bootstrap(f, labels, other, base, speakers, n_resamples=n_boot)
                for name, f in METRICS.items()
            }
        results["conditions"][condition] = entry
    return results


def _pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def _pts(i: Interval) -> str:
    def f(v: float) -> str:
        return f"{round(100 * v, 1) + 0.0:+.1f}"  # + 0.0 turns -0.0 into 0.0

    verdict = "" if i.low <= 0 <= i.high else " *"
    return f"{f(i.estimate)} ({f(i.low)} to {f(i.high)}){verdict}"


def write_markdown(r: dict, path: Path) -> None:
    models, baseline = r["models"], r["baseline"]
    short = {m: m.removeprefix("antideepfake-") for m in models}
    lines = [
        "# Phase 2 bake-off: In-the-Wild test speakers",
        "",
        "*Generated by `eval/compare.py`. Clean audio covers every test-speaker clip; each codec",
        "covers the same 3,000-clip stratified test sample for every model. Choices were made on",
        "dev speakers; these numbers are test speakers only.*",
    ]
    for name in METRICS:
        lines += ["", f"## {name}", "", _row("Condition", *(short[m] for m in models))]
        lines.append(_row(*(["---"] * (len(models) + 1))))
        for entry in r["conditions"].values():
            cells = (_pct(entry["metrics"][m][name]) for m in models)
            lines.append(_row(entry["description"], *cells))
    lines += [
        "",
        f"## Difference from {short[baseline]} (paired speaker bootstrap, 95% intervals)",
        "",
        f"Percentage points, other model minus {short[baseline]}. For EER, positive means the "
        f"other model makes more errors; for fakes caught, negative means it catches fewer. "
        "\\* marks intervals that exclude zero.",
        "",
    ]
    others = [m for m in models if m != baseline]
    header = [f"{short[m]}: {name}" for m in others for name in METRICS]
    lines += [_row("Condition", *header), _row(*(["---"] * (len(header) + 1)))]
    for entry in r["conditions"].values():
        cells = (_pts(entry["vs_baseline"][m][name]) for m in others for name in METRICS)
        lines.append(_row(entry["description"], *cells))
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def _row(*cells: object) -> str:
    return "| " + " | ".join(str(c) for c in cells) + " |"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Compare models on the same evaluation clips.")
    parser.add_argument("--models", nargs="+", default=list(MODELS))
    parser.add_argument("--baseline", default=DEFAULT_MODEL)
    parser.add_argument("--bootstrap", type=int, default=1000)
    args = parser.parse_args(argv)
    models = [args.baseline] + [m for m in args.models if m != args.baseline]
    results = compare(Settings.from_env().data_dir, models, args.baseline, args.bootstrap)
    out = RESULTS_DIR / "bakeoff.md"
    write_markdown(results, out)
    print(f"Wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
