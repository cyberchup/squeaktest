"""Write eval/results/<model>/report.md and plots from the analysis results."""

from __future__ import annotations

from pathlib import Path


def _pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def _ci(m: dict, pct: bool = True) -> str:
    f = _pct if pct else (lambda v: f"{v:.3f}")
    return f"{f(m['estimate'])} ({f(m['low'])} to {f(m['high'])})"


def _row(*cells: object) -> str:
    return "| " + " | ".join(str(c) for c in cells) + " |"


def _header(*names: str) -> list[str]:
    return [_row(*names), _row(*(["---"] * len(names)))]


def write_report(r: dict, path: Path) -> None:
    t = r["test_clean"]
    cov = t["coverage"]
    base = r["length_baseline_test"]
    lines = [
        f"# Evaluation: {r['model']} on In-the-Wild",
        "",
        "*Generated by `eval/analyze.py`. Test speakers only, unless marked dev. Brackets are 95%",
        "confidence intervals from resampling whole speakers. Scores are raw (uncalibrated) unless",
        "marked calibrated.*",
        "",
        "## Headline (clean audio, test speakers)",
        "",
        *_header("Metric", "Value"),
        _row("Clips scored", f"{t['clips']:,} ({t['fakes']:,} fake) from {t['speakers']} speakers"),
        _row("EER", _ci(t["eer"])),
        _row("ROC-AUC", _ci(t["auc"], pct=False)),
        _row("Fakes caught at 1% false positives", _ci(t["tpr_at_1pct_fpr"])),
        _row("Fakes caught at 5% false positives", _ci(t["tpr_at_5pct_fpr"])),
        _row(
            "Not assessed (too little sound)",
            f"genuine {_pct(cov['genuine']['share'])} ({cov['genuine']['not_assessed']:,}), "
            f"synthetic {_pct(cov['synthetic']['share'])} ({cov['synthetic']['not_assessed']:,})",
        ),
        "",
        "## Shortcut check: clip length",
        "",
        f"Clip duration alone, with no model: AUC {base['auc']:.3f}, EER {_pct(base['eer'])}. "
        "Correlation between score and duration among genuine clips (Spearman): "
        f"{r['genuine_score_vs_duration_spearman']:+.2f}.",
        "",
        *_header("Duration", "Clips", "Fake share", "EER", "AUC"),
    ]
    for b in r["by_duration_test"]:
        low, high = b["seconds"]
        label = f"{low}-{high} s" if high else f"{low} s and up"
        share, err, auc = _pct(b["fake_share"]), _pct(b["eer"]), f"{b['auc']:.3f}"
        lines.append(_row(label, f"{b['clips']:,}", share, err, auc))

    lines += ["", "## Aggregation (decision D6)", ""]
    lines += _header("Method", "EER", "AUC", "Fakes caught at 1% FPR")
    for name, m in r["aggregation_test"].items():
        lines.append(_row(name, _pct(m["eer"]), f"{m['auc']:.4f}", _pct(m["tpr_at_1pct_fpr"])))

    lines += ["", "## Minimum sound per clip (decision D5, dev speakers)", ""]
    lines += _header("Minimum", "EER", "Genuine not assessed", "Synthetic not assessed")
    for m in r["min_speech_dev"]:
        lines.append(
            _row(
                f"{m['min_speech_s']:g} s",
                _pct(m["eer"]),
                _pct(m["not_assessed_genuine"]),
                _pct(m["not_assessed_synthetic"]),
            )
        )

    c = r["calibration"]
    b = r["bands"]
    th, rules = b["thresholds"], b["rules"]
    lines += [
        "",
        "## Calibration (fitted on dev, measured on test)",
        "",
        f"Platt scaling: a = {c['platt']['a']:.3f}, b = {c['platt']['b']:.3f}, fitted on dev data "
        f"that is {_pct(c['platt']['fitted_fake_share'])} fake.",
        "",
        *_header("", "ECE", "Brier"),
        _row("Raw", f"{c['test_raw']['ece']:.3f}", f"{c['test_raw']['brier']:.3f}"),
        _row(
            "Calibrated",
            f"{c['test_calibrated']['ece']:.3f}",
            f"{c['test_calibrated']['brier']:.3f}",
        ),
        "",
        "## Bands (thresholds chosen on dev, applied to test)",
        "",
        f"*Likely synthetic* at calibrated score {th['likely_synthetic_at']:.3f} or above (at most "
        f"{_pct(rules['likely_synthetic_max_dev_fpr'])} of genuine dev clips). *Likely genuine* "
        f"below {th['likely_genuine_below']:.3f} (at least "
        f"{_pct(rules['likely_genuine_min_dev_fake_recall'])} of dev fakes stay above it).",
        "",
        *_header("Test clips", "Likely synthetic", "Uncertain", "Likely genuine"),
    ]
    for name in ("genuine", "synthetic"):
        row = b["test"][name]
        cells = (_pct(row[k]) for k in ("likely_synthetic", "uncertain", "likely_genuine"))
        lines.append(_row(name.capitalize(), *cells))

    op = b["test_at_synthetic_threshold"]
    lines += [
        "",
        f"At the *likely synthetic* threshold: test false-positive rate {_pct(op['fpr'])}, "
        f"detection rate {_pct(op['tpr'])}. Share of alerts that would be real fakes at different "
        "base rates:",
        "",
        *_header("Share of recordings that are fake", "Share of alerts that are fakes"),
    ]
    for prevalence, precision in r["base_rates"].items():
        lines.append(_row(f"{float(prevalence):g}", _pct(precision)))

    if r["conditions"]:
        lines += ["", "## Phone and compression conditions (3,000-clip test sample)", ""]
        lines += _header(
            "Condition",
            "EER",
            "Same clips, clean",
            "AUC",
            "Fakes caught at 1% FPR",
            "Genuine flagged at clean threshold",
        )
        for cnd in r["conditions"].values():
            m = cnd["metrics"]
            lines.append(
                _row(
                    cnd["description"],
                    _ci(m["eer"]),
                    _pct(cnd["same_clips_clean"]["eer"]),
                    f"{m['auc']['estimate']:.3f}",
                    _pct(m["tpr_at_1pct_fpr"]["estimate"]),
                    _pct(cnd["at_clean_dev_thresholds"]["fpr"]),
                )
            )
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_plots(r: dict, out_dir: Path) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    fig, ax = plt.subplots(figsize=(5, 5))
    ax.plot([0, 1], [0, 1], color="#999999", linestyle="--", linewidth=1, label="perfect")
    for key, label, color in (
        ("reliability_raw", "raw", "#d95f02"),
        ("reliability_calibrated", "calibrated", "#1b9e77"),
    ):
        bins = r["calibration"][key]
        x = [b["mean_predicted"] for b in bins]
        y = [b["fraction_synthetic"] for b in bins]
        ax.plot(x, y, marker="o", color=color, label=label)
    ax.set_xlabel("predicted probability of synthetic")
    ax.set_ylabel("observed share of synthetic clips")
    ax.set_title("Reliability (In-the-Wild test speakers)")
    ax.legend(loc="upper left")
    fig.tight_layout()
    fig.savefig(out_dir / "reliability.png", dpi=150)
    plt.close(fig)

    buckets = r["by_duration_test"]
    if buckets:
        fig, ax = plt.subplots(figsize=(6, 3.5))
        labels = []
        for b in buckets:
            low, high = b["seconds"]
            labels.append(f"{low}-{high} s" if high else f"{low}+ s")
        ax.bar(labels, [100 * b["eer"] for b in buckets], color="#7570b3")
        ax.set_ylabel("EER (%)")
        ax.set_title("EER by clip duration (test speakers)")
        fig.tight_layout()
        fig.savefig(out_dir / "eer_by_duration.png", dpi=150)
        plt.close(fig)
